export function translate(language: "zh-CN" | "en", key: MessageKey, values: Record<string, string | number> = {}): string {
  const template: string = language === "en" ? en[key] : zhCN[key];
  return template.replace(/\{([a-zA-Z][\w]*)\}/g, (placeholder, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : placeholder,
  );
}
